/**
 * Definition for singly-linked list.
 * struct ListNode {
 *     int val;
 *     ListNode *next;
 *     ListNode() : val(0), next(nullptr) {}
 *     ListNode(int x) : val(x), next(nullptr) {}
 *     ListNode(int x, ListNode *next) : val(x), next(next) {}
 * };
 */
class Solution {
public:
    int getDecimalValue(ListNode* head) { // t.c - 0(n), s.c - 0(1)
        int ans = 0;

        while(head != NULL){
            ans = ans*2 + head->val; // 0 * 2 + 1 -> 1, 1 * 2 + 0 -> 2 etc
            head = head->next;
        }
        return ans;
    }
};

